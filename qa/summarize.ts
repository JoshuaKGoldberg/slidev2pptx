/**
 * Summarizes every corpus deck's round-trip report into qa/reports/summary.md.
 * @example
 * ```shell
 * node qa/summarize.ts
 * ```
 */
import fs from "node:fs/promises";
import path from "node:path";

import type { Deck } from "./corpus/types.ts";

import { manifestPath } from "./corpus/paths.ts";
import { reportsDirectory } from "./reports/paths.ts";

interface Report {
	build: { clicks: { problems: { severity: string }[]; seconds?: number } };
	conversion: { losses: number; missingFonts: string[] };
	counts: { original: number; pptx: number; slidev: number };
	slidevErrors: string[];
	states: {
		name: string;
		step2?: { changed: number; ssim: number };
		verdict: string;
	}[];
	summary: Record<"fail" | "missing" | "pass" | "review", number>;
}

const manifest = JSON.parse(await fs.readFile(manifestPath, "utf8")) as Deck[];
const runs = path.join(import.meta.dirname, "runs");
const rows: string[] = [];
const totals = { fail: 0, missing: 0, pass: 0, review: 0 };
const notRun: string[] = [];

for (const deck of manifest) {
	const report = await fs
		.readFile(path.join(runs, deck.id, "report.json"), "utf8")
		.then((text) => JSON.parse(text) as Report)
		.catch(() => undefined);
	if (!report) {
		notRun.push(`${deck.id}${deck.sha256 ? "" : " (not downloaded)"}`);
		continue;
	}

	for (const key of Object.keys(totals) as (keyof typeof totals)[]) {
		totals[key] += report.summary[key];
	}

	const similarities = report.states
		.flatMap((state) => (state.step2 ? [state.step2.ssim] : []))
		.sort((a, b) => a - b);
	const errors = report.build.clicks.problems.filter(
		(problem) => problem.severity === "error",
	).length;
	rows.push(
		`| ${deck.id} | ${String(report.counts.slidev)} | ${String(report.summary.pass)} | ${String(report.summary.review)} | ${String(report.summary.fail)} | ${String(report.summary.missing)} | ${similarities.length ? similarities[Math.floor(similarities.length / 2)].toFixed(3) : "-"} | ${similarities.length ? similarities[0].toFixed(3) : "-"} | ${String(errors)} | ${String(report.slidevErrors.length)} | ${String(report.conversion.losses)} |`,
	);
}

const markdown = [
	"# Round-Trip Summary",
	"",
	"Generated by `node qa/summarize.ts` from `qa/runs/*/report.json`.",
	"Each state is one click state of one slide: its Slidev rendering (Chromium) against slidev2pptx's (PowerPoint).",
	"",
	`Totals: ${String(totals.pass)} pass, ${String(totals.review)} review, ${String(totals.fail)} fail, ${String(totals.missing)} missing.`,
	"",
	"| Deck | States | Pass | Review | Fail | Missing | Median SSIM | Worst SSIM | Build errors | Slidev errors | Conversion losses |",
	"| ---- | -----: | ---: | -----: | ---: | ------: | ----------: | ---------: | -----------: | ------------: | ----------------: |",
	...rows,
	"",
	...(notRun.length
		? ["Not run:", "", ...notRun.map((id) => `- ${id}`), ""]
		: []),
].join("\n");

await fs.writeFile(path.join(reportsDirectory, "summary.md"), markdown);
console.log(
	`Summarized ${String(rows.length)} decks: ${JSON.stringify(totals)}.`,
);
